/**
 * 提出のあとに書かれた記録を、取り残さないこと。
 *
 * ## なぜ毎回起きるか
 *
 * トークンの記録はフック（Stop / SessionEnd）が書く。**順番が決まっている。**
 *
 *   1. コミットする
 *   2. 提出する
 *   3. 人に報告して止まる → ここでフックが走り、追記される
 *   4. 次の作業へ移る。ブランチが変わる
 *
 * **3 は必ず 1 の後に来る。** したがって、最後の1件は構造的にコミットされない。
 * 忘れたからではない（AUT-156）。
 *
 * **この順番自体は変わっていない。** 変えたのは、フックの書き先である。
 *
 * ## 実際にどうなっていたか
 *
 * 記録は消えてはいなかった。`begin` が既定ブランチを最新にしてからブランチを作るため、
 * 未コミットの追記はそのまま次のブランチへ持ち越され、**次の作業単位のコミットに紛れて
 * 入っていた。** 拾えていたのは、たまたま次の作業がそこにあったからである。
 *
 * ## 拾う形をやめた（AUT-162）
 *
 * 以前は `begin` が拾ってコミットしていた。**それは、別の作業単位の記録を、いま
 * 着手した作業単位の提出に載せる形である。** 参照実装で数えると、トークン記録
 * 115 行のうち 93 行（81%）が別の作業単位のコミットで入っていた。
 *
 * 拾えるのは、**同じ作業ツリーが残っている場合に限られる。** 作業単位ごとに
 * ワークツリーを作って捨てる並列実行では、次の `begin` が無いので拾う機会その
 * ものが消える。**並列度が上がるほど欠損が増える。**
 *
 * ここに書いていた「記録の置き場を履歴の外へ移さない」という判断も、取り下げた。
 * **定義§16の記録規約は、テレメトリの置き場所を Telemetry ポートとしている。**
 * Repo ではない。リポジトリの中にあったのはアダプタの選択にすぎなかった。
 *
 * ## いま何が残っているか
 *
 * **トークン消費は、もうここへ書かれない。** 行き先はリポジトリの外になった
 * （`adapters/tokensOtlp.js`）。あわせて定義 v0.16 で任意の記録対象になっている。
 *
 * したがって `telemetry/` へ書くのは、**その作業単位で動いているAI自身**に限る。
 * 自分で書いたものは、自分でコミットできる。**拾う相手が居ない。**
 *
 * それでも残ることはあるので、**あることだけを言う。拾わない。** 拾って隠すと、
 * 混ざったことにも気づけない。
 *
 * ## 他のリポジトリの取り残し
 *
 * **ここでは触らない。** 1つの作業単位が変更を書き込むリポジトリは1つに限るため
 * である（`CLAUDE.md`）。**代わりに、あることを言う。** 黙ると、そのリポジトリで
 * 次の作業が起きるまで誰も知らない。
 */

/** 記録ファイルかどうか。**`telemetry/` の直下の `.jsonl` だけを見る。** */
const TELEMETRY = /^telemetry\/[^/]+\.jsonl$/;

/**
 * 未コミットの記録ファイル。
 *
 * `git status --porcelain -uall` の出力を読む。**追跡されていないものも拾う。**
 * 新しい作業単位の1件目は、ファイルごと新しい。
 *
 * **記録以外には触らない。** 手元に残っている他の変更は、拾う対象ではない。
 * まとめてコミットすると、作業中のものを勝手に履歴へ載せることになる。
 */
export function strandedFiles(porcelain) {
  const found = [];
  for (const line of (porcelain ?? "").split("\n")) {
    if (line.length < 4) continue;
    // `XY PATH`。名前が変わったものは `XY ORIG -> PATH` になる。
    let path = line.slice(3).trim();
    const arrow = path.indexOf(" -> ");
    if (arrow !== -1) path = path.slice(arrow + 4).trim();
    // 引用符付きで出ることがある（空白や非 ASCII を含む場合）。
    if (path.startsWith('"') && path.endsWith('"')) path = path.slice(1, -1);
    if (!TELEMETRY.test(path)) continue;
    if (!found.includes(path)) found.push(path);
  }
  return found;
}


/** 他のリポジトリの取り残しを、読める形にする。 */
export function describeOthers(entries) {
  const found = entries.filter((e) => e.files.length > 0);
  if (found.length === 0) return [];
  return [
    "",
    "**他のリポジトリに、取り残された記録がある。** ここでは拾えない（1つの作業単位が",
    "書き込むリポジトリは1つに限るため）。そのリポジトリで次に着手したときに乗る。",
    ...found.flatMap((e) => [`  ${e.name}`, ...e.files.map((f) => `    ${f}`)]),
  ];
}

/**
 * 取り残された記録があれば、**言う。コミットはしない。**
 *
 * ## なぜ拾うのをやめたか
 *
 * 拾う形は、**別の作業単位の記録を、いま着手した作業単位の提出に載せる。** 参照
 * 実装で数えると、トークン記録 115 行のうち 93 行（81%）が別の作業単位のコミットで
 * 入っていた。**作業と無関係の変更が提出に混ざるため、読む人に説明が要る。**
 * 説明が要る時点で、形として歪んでいる。
 *
 * 誤認も生む。提出の差分を読んだ人は、その作業単位が触ったものだと読む。
 *
 * **そして、拾う相手がもう居ない。** 提出の後に書いていたのはフックのトークン記録
 * だけで、それはリポジトリの外へ出た（`adapters/tokensOtlp.js`、AUT-162）。
 * ここへ書くのは、いまや**その作業単位で動いているAI自身**に限る。自分で書いた
 * ものは、自分でコミットできる。
 *
 * ## 黙らない理由
 *
 * それでも残ることはある。**残ったら、そのまま次のブランチへ持ち越される。**
 * 気づかなければ、いずれどこかの提出に混ざる。
 *
 * **防ぐのではなく、気づける形にする。** 拾って隠すと、混ざったことも気づけない。
 *
 * @param {string} repoPath 対象リポジトリ
 * @param {(repoPath: string, args: string[]) => string} git
 * @returns {string[]} 報告の行
 */
export function detect(repoPath, git) {
  let status;
  try {
    status = git(repoPath, ["status", "--porcelain", "-uall"]);
  } catch (error) {
    return ["", `取り残された記録を調べられなかった: ${message(error)}`];
  }

  const files = strandedFiles(status);
  if (files.length === 0) return [];

  return [
    "",
    "**取り残された記録がある。** ここでは拾わない（別の作業単位の提出に混ざるため）。",
    ...files.map((f) => `  ${f}`),
    "どの作業単位のものかを確かめること。いま着手したものなら、この作業の変更と",
    "一緒に提出してよい。別の作業単位のものなら、**そちらのブランチへ載せること。**",
  ];
}

/** 例外から読める文を取り出す。 */
function message(error) {
  return error instanceof Error ? error.message : String(error);
}
